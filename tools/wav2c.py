#!/usr/bin/env python3
"""Convert WAV files to 8 kHz unsigned 8-bit PCM C arrays for the flash-resident audio.

Layout (folders under --in):
    audio/notthat/*.wav   "not that one" + variants
    audio/wait/*.wav      "wait"

    python3 tools/wav2c.py                 # real audio
    python3 tools/wav2c.py --placeholder   # synthesise stand-ins so the firmware builds

Needs PCM WAV (8/16/24/32-bit int). For anything else:
    ffmpeg -i in.mp3 -ac 1 -ar 8000 -c:a pcm_s16le out.wav
Standard library only.
"""
import argparse
import array
import math
import random
import sys
import wave
from itertools import accumulate
from pathlib import Path

RATE = 8000
# folder, C suffix, crossfade-for-loop
CATEGORIES = [
    ("notthat", "NOTTHAT", False),
    ("wait", "WAIT", False),
]


def read_wav(path):
    with wave.open(str(path), "rb") as w:
        ch, sw, sr, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        raw = w.readframes(n)
    if sw == 1:
        x = [(b - 128) / 128.0 for b in raw]
    elif sw == 2:
        a = array.array("h")
        a.frombytes(raw)
        if sys.byteorder == "big":
            a.byteswap()
        x = [v / 32768.0 for v in a]
    elif sw == 3:
        x = [int.from_bytes(raw[i:i + 3], "little", signed=True) / 8388608.0 for i in range(0, len(raw), 3)]
    elif sw == 4:
        a = array.array("i")
        a.frombytes(raw)
        if sys.byteorder == "big":
            a.byteswap()
        x = [v / 2147483648.0 for v in a]
    else:
        raise ValueError(f"{path}: unsupported sample width {sw}")
    if ch > 1:
        x = [sum(x[i:i + ch]) / ch for i in range(0, len(x) - ch + 1, ch)]
    return x, sr


def resample(x, sr):
    """Area-average resample: a box low-pass, good enough to keep aliasing down at 8 kHz."""
    if sr == RATE:
        return x
    ratio = sr / RATE
    n_out = int(len(x) / ratio)
    cs = [0.0] + list(accumulate(x))

    def cum(pos):
        i = int(pos)
        if i >= len(x):
            return cs[-1]
        return cs[i] + x[i] * (pos - i)

    return [(cum((k + 1) * ratio) - cum(k * ratio)) / ratio for k in range(n_out)]


def crossfade_loop(x, seconds=0.75):
    n = min(int(seconds * RATE), len(x) // 3)
    if n < 2:
        return x
    head = len(x) - n
    out = x[:head]
    for i in range(n):
        a = i / n
        out[i] = a * x[i] + (1 - a) * x[head + i]
    return out


def process(x, sr, loop, peak):
    x = resample(x, sr)
    if not x:
        raise ValueError("empty clip")
    mean = sum(x) / len(x)
    x = [v - mean for v in x]
    if loop:
        x = crossfade_loop(x)
    top = max(abs(v) for v in x) or 1.0
    k = peak / top
    x = [v * k for v in x]
    if not loop:  # 5 ms edges avoid clicks; loops are already seamless
        n = int(0.005 * RATE)
        for i in range(min(n, len(x))):
            f = i / n
            x[i] *= f
            x[-1 - i] *= f
    return x


def quantise(x, dither):
    out = bytearray()
    for v in x:
        q = v * 127.0 + 128.0
        if dither:
            q += random.random() - 0.5
        out.append(max(0, min(255, int(round(q)))))
    return bytes(out)


# ------------------------------------------------------------------ placeholders
def synth_murmur(seconds, seed):
    rng = random.Random(seed)
    n = seconds * RATE
    y, out = 0.0, []
    am_f1, am_f2 = rng.uniform(0.15, 0.35), rng.uniform(0.4, 0.8)
    for i in range(n):
        y += 0.12 * (rng.uniform(-1, 1) - y)  # one-pole low-pass noise
        t = i / RATE
        am = 0.55 + 0.3 * math.sin(2 * math.pi * am_f1 * t) + 0.15 * math.sin(2 * math.pi * am_f2 * t)
        out.append(y * am)
    return out


def synth_tone(seconds, f0, f1):
    n = int(seconds * RATE)
    ph, out = 0.0, []
    for i in range(n):
        f = f0 + (f1 - f0) * i / n
        ph += 2 * math.pi * f / RATE
        env = math.sin(math.pi * i / n)
        out.append(math.sin(ph) * env * (0.7 + 0.3 * math.sin(2 * math.pi * 6 * i / RATE)))
    return out


def placeholders():
    return {
        "notthat": [(f"placeholder_notthat_{i}", synth_tone(0.9, 300 - 40 * i, 200 - 30 * i)) for i in range(3)],
        "wait": [("placeholder_wait", synth_tone(0.7, 180, 240))],
    }


# ------------------------------------------------------------------------ output
def emit(clips_by_cat, out_path, dither):
    total = 0
    lines = [
        "// GENERATED by tools/wav2c.py - do not edit.",
        '#include "audio_data.h"',
        "",
    ]
    for folder, suffix, _loop in CATEGORIES:
        entries = clips_by_cat.get(folder, [])
        names = []
        for idx, (name, pcm) in enumerate(entries):
            total += len(pcm)
            arr = f"{folder}_{idx}"
            names.append((arr, len(pcm)))
            lines.append(f"// {name}: {len(pcm)} bytes, {len(pcm) / RATE:.1f} s")
            lines.append(f"static const uint8_t {arr}[] = {{")
            for i in range(0, len(pcm), 24):
                lines.append("  " + ",".join(str(b) for b in pcm[i:i + 24]) + ",")
            lines.append("};")
            lines.append("")
        lines.append(f"const Clip CLIPS_{suffix}[] = {{")
        if names:
            lines += [f"  {{{a}, {n}}}," for a, n in names]
        else:
            lines.append("  {nullptr, 0},")
        lines.append("};")
        lines.append(f"const uint8_t N_{suffix} = {len(names)};")
        lines.append("")
    out_path.write_text("\n".join(lines))
    return total


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--in", dest="indir", default="audio", type=Path)
    ap.add_argument("--out", default="src/audio_data.cpp", type=Path)
    ap.add_argument("--peak", type=float, default=0.9, help="normalise each clip to this peak (0-1)")
    ap.add_argument("--no-dither", action="store_true")
    ap.add_argument("--budget", type=int, default=3_500_000, help="warn if total bytes exceed this")
    ap.add_argument("--placeholder", action="store_true", help="synthesise stand-in audio")
    args = ap.parse_args()

    random.seed(1)
    clips = {}
    if args.placeholder:
        for folder, _s, loop in CATEGORIES:
            clips[folder] = [(n, quantise(process(x, RATE, loop, args.peak), not args.no_dither))
                             for n, x in placeholders()[folder]]
    else:
        for folder, _s, loop in CATEGORIES:
            files = sorted((args.indir / folder).glob("*.wav"))
            clips[folder] = []
            for f in files:
                x, sr = read_wav(f)
                clips[folder].append((f.name, quantise(process(x, sr, loop, args.peak), not args.no_dither)))
            print(f"{folder:8s} {len(files)} clip(s)")
    total = emit(clips, args.out, not args.no_dither)
    print(f"wrote {args.out}: {total} bytes audio = {total / RATE:.0f} s "
          f"(app partition holds ~3.7 MB incl. code)")
    if total > args.budget:
        sys.exit(f"ERROR: over budget ({total} > {args.budget}). Shorten or drop clips.")


if __name__ == "__main__":
    main()
